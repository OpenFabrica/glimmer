//! 英文评测文本切出来的一段：要评的词，或跳过的原文。

/// 文本按空白切开后的一段。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Piece {
    /// 要评的词（纯字母或带撇号）。
    Word {
        /// 词前面紧挨着的标点（`"hello` 的 `"`），敲词之前原样直通给应用。
        head: String,

        /// 词本身，大小写照原文；模拟用户就按这串字母敲。
        text: String,

        /// 词后面紧挨着的标点加一个分隔（空格，行尾是换行），上屏之后原样直通。
        tail: String,
    },

    /// 不评的原文（数字、带连字符或非 ASCII 字母的词、纯标点），连同后面的分隔原样直通；它也把上文断开。
    Gap(String),
}
